#!/usr/bin/env node
/**
 * Builds the SmartMenu owl — front view, rigged for animation — into:
 *   public/assistant/owl-mascot.svg              standalone SVG (design review, exports)
 *   src/components/mascot/owl-art.generated.ts   the same art for the <Owl> component
 *
 * Traced from the FRONT VIEW of reference-sheet.png (next to this file): the crop
 * (22,640)-(252,945) scaled 3x, so the viewBox 0 0 690 915 is that crop's pixel
 * grid. The owl is symmetric about x = 345: right-side parts are the left parts
 * mirrored (lib/geometry.mjs), so edit the left side only.
 *
 *   node scripts/mascot/build-owl-svg.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { defsMarkup } from './lib/defs.mjs'
import { figureMarkup } from './lib/figure.mjs'
import { fxMarkup } from './lib/fx.mjs'
import { clipDefs } from './lib/parts.mjs'
import { RIG } from './lib/rig.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const SVG_OUT = join(ROOT, 'public/assistant/owl-mascot.svg')
const TS_OUT = join(ROOT, 'src/components/mascot/owl-art.generated.ts')
const VIEWBOX = '0 0 690 915'

/**
 * Tag every blurred element `o-soft`: the small ("lite") owl drops them, since
 * blur filters cost more than they show at icon size.
 */
const markSoft = (markup) =>
  markup.replace(/<(path|ellipse|circle|rect)\s((?:(?!\/>)[^>])*?filter="url\(#f-[a-z]+\)"[^>]*)\/>/g, '<$1 class="o-soft" $2/>')

// Parts register their clip paths while rendering, so render them before <defs>.
const figure = figureMarkup()
const fx = fxMarkup()
const clips = [...clipDefs].map(([k, d]) => `<clipPath id="clip-${k}"><path d="${d}"/></clipPath>`).join('\n    ')
const inner = markSoft(`${defsMarkup(clips)}\n${figure}\n${fx}`)

const rigList = Object.entries(RIG)
  .map(([id, e]) => `      ${id.padEnd(20)} ${e ? `pivot ${e[0]} ${e[1]}${e[2]?.hidden ? ', starts hidden' : ''}` : '(static group)'}`)
  .join('\n')

const svg = `<svg xmlns="http://www.w3.org/2000/svg" id="owl" viewBox="${VIEWBOX}" width="690" height="915" role="img" aria-labelledby="owl-title">
  <title id="owl-title">Owl, the SmartMenu mascot</title>
  <!--
    GENERATED by scripts/mascot/build-owl-svg.mjs — edit that, not this file.

    Every rigged part is <g id="X" class="o-X"> with its transform-origin set
    inline; no rigged group carries a transform attribute. Parts:
${rigList}
  -->
${inner}
</svg>
`

const ts = `// GENERATED by scripts/mascot/build-owl-svg.mjs — do not edit by hand.
// The owl's SVG contents (everything inside <svg>), trusted static markup.

export const OWL_VIEWBOX = '${VIEWBOX}'

export const OWL_MARKUP = ${JSON.stringify(inner.replace(/\n\s*/g, '\n'))}
`

writeFileSync(SVG_OUT, svg)
writeFileSync(TS_OUT, ts)
console.log(`wrote ${SVG_OUT}\nwrote ${TS_OUT}`)
